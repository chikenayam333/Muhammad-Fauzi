    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
    int baris = tblOrder.getSelectedRow();
    if (baris < 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Pilih order di tabel dulu");
        return;
    }

    Integer estimasi = null;
    String teks = txtEstimasi.getText().trim();
    if (!teks.isEmpty()) {
        try {
            estimasi = Integer.parseInt(teks);
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Estimasi harus berupa angka (hari)");
            return;
        }
    }

    OrderEntity o = orderDao.cariById((int) tblOrder.getValueAt(baris, 0));
    String statusLama = o.getStatus();
    String statusBaru = cmbStatus.getSelectedItem().toString();

    o.setStatus(statusBaru);
    o.setEstimasiHari(estimasi);
    orderDao.ubah(o);

    // order ditolak: kembalikan stok yang tadi dikurangi saat user memesan
    if ("Ditolak".equals(statusBaru) && !"Ditolak".equals(statusLama)) {
        StikerEntity s = stikerDao.cariById(o.getStiker().getId());
        s.setStok(s.getStok() + o.getJumlah());
        stikerDao.ubah(s);
    }

    loadTabelOrder();
    txtEstimasi.setText("");
    javax.swing.JOptionPane.showMessageDialog(this, "Order berhasil diperbarui");

        // TODO add your handling code here:
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnLihatGambarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLihatGambarActionPerformed
    int baris = tblOrder.getSelectedRow();
    if (baris < 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Pilih order di tabel dulu");
        return;
    }
    OrderEntity o = orderDao.cariById((int) tblOrder.getValueAt(baris, 0));
    if (o.getGambarPath() == null) {
        javax.swing.JOptionPane.showMessageDialog(this, "User tidak melampirkan gambar");
        return;
    }
    java.io.File f = new java.io.File(o.getGambarPath());
    if (!f.exists()) {
        javax.swing.JOptionPane.showMessageDialog(this, "File gambar tidak ditemukan");
        return;
    }
    javax.swing.ImageIcon icon = new javax.swing.ImageIcon(f.getAbsolutePath());
    java.awt.Image kecil = icon.getImage().getScaledInstance(400, -1, java.awt.Image.SCALE_SMOOTH);
    javax.swing.JOptionPane.showMessageDialog(this, new javax.swing.JLabel(new javax.swing.ImageIcon(kecil)),
            "Design Order #" + o.getId(), javax.swing.JOptionPane.PLAIN_MESSAGE);

        // TODO add your handling code here:
    }//GEN-LAST:event_btnLihatGambarActionPerformed

